/// The unified result returned by every [SAIEEngine] public method.
final class EngineResult extends Equatable {
  /// The assistant response text to display to the student.
  final String assistantResponse;

  /// The current conversation stage.
  final ConversationStage currentPhase;

  /// Assessment progress (questions asked, coverage, confidence, etc.).
  final AssessmentProgress assessmentProgress;

  /// Decision confidence from the Decision Engine.
  final DecisionConfidence confidence;

  /// Whether a recommendation is ready.
  final bool recommendationAvailable;

  /// The currently active assessment question (null if not in assessment).
  final Question? currentQuestion;

  /// The active response language.
  final ConversationLanguage currentLanguage;

  /// Lightweight profile snapshot for the UI.
  final EngineStudentSnapshot studentSnapshot;

  /// The event generated by this turn.
  final EngineEvent? event;

  /// The full recommendation report (non-null when [recommendationAvailable]).
  final RecommendationReport? recommendationReport;

  const EngineResult({
    required this.assistantResponse,
    required this.currentPhase,
    required this.assessmentProgress,
    required this.confidence,
    required this.recommendationAvailable,
    required this.currentLanguage,
    required this.studentSnapshot,
    this.currentQuestion,
    this.event,
    this.recommendationReport,
  });

  factory EngineResult.fromJson(Map<String, dynamic> json) => EngineResult(
    assistantResponse: json['assistant_response'] as String,
    currentPhase:
        ConversationStage.values.byName(json['current_phase'] as String),
    assessmentProgress: AssessmentProgress.fromJson(
      json['assessment_progress'] as Map<String, dynamic>,
    ),
    confidence: DecisionConfidence.fromJson(
      json['confidence'] as Map<String, dynamic>,
    ),
    recommendationAvailable: json['recommendation_available'] as bool,
    currentLanguage: ConversationLanguage.fromJson(
      json['current_language'] as Map<String, dynamic>,
    ),
    studentSnapshot: EngineStudentSnapshot.fromJson(
      json['student_snapshot'] as Map<String, dynamic>,
    ),
  );

  Map<String, dynamic> toJson() => {
    'assistant_response': assistantResponse,
    'current_phase': currentPhase.name,
    'assessment_progress': assessmentProgress.toJson(),
    'recommendation_available': recommendationAvailable,
    'current_language': currentLanguage.toJson(),
    'student_snapshot': studentSnapshot.toJson(),
  };

  EngineResult copyWith({
    String? assistantResponse,
    ConversationStage? currentPhase,
    AssessmentProgress? assessmentProgress,
    DecisionConfidence? confidence,
    bool? recommendationAvailable,
    Question? currentQuestion,
    ConversationLanguage? currentLanguage,
    EngineStudentSnapshot? studentSnapshot,
    EngineEvent? event,
    RecommendationReport? recommendationReport,
  }) => EngineResult(
    assistantResponse: assistantResponse ?? this.assistantResponse,
    currentPhase: currentPhase ?? this.currentPhase,
    assessmentProgress: assessmentProgress ?? this.assessmentProgress,
    confidence: confidence ?? this.confidence,
    recommendationAvailable:
        recommendationAvailable ?? this.recommendationAvailable,
    currentQuestion: currentQuestion ?? this.currentQuestion,
    currentLanguage: currentLanguage ?? this.currentLanguage,
    studentSnapshot: studentSnapshot ?? this.studentSnapshot,
    event: event ?? this.event,
    recommendationReport: recommendationReport ?? this.recommendationReport,
  );

  @override
  List<Object?> get props => [assistantResponse, currentPhase];
}
