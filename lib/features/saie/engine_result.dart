/// A lightweight read-only view of the student profile for the UI.
/// Distinct from the internal [StudentSnapshot] in profile layer.
final class EngineStudentSnapshot extends Equatable {
  final String studentId;
  final Map<String, double> topDimensions;
  final String? dominantLearningStyle;
  final double overallConfidence;

  const EngineStudentSnapshot({
    required this.studentId,
    required this.topDimensions,
    required this.overallConfidence,
    this.dominantLearningStyle,
  });

  factory EngineStudentSnapshot.fromProfile(StudentCognitiveProfile profile) =>
      EngineStudentSnapshot(
        studentId: profile.studentId,
        topDimensions: _topDimensions(profile),
        overallConfidence: profile.computeStatistics().overallConfidence,
        dominantLearningStyle:
            profile.learningStyle.dominantModality?.name,
      );

  static Map<String, double> _topDimensions(StudentCognitiveProfile p) {
    final all = DimensionKeys.all
        .map((k) => MapEntry(k, p.scoreFor(k)))
        .where((e) => e.value > 0)
        .toList()
      ..sort((a, b) => b.value.compareTo(a.value));
    return Map.fromEntries(all.take(5));
  }

  factory EngineStudentSnapshot.fromJson(Map<String, dynamic> json) =>
      EngineStudentSnapshot(
        studentId: json['student_id'] as String,
        topDimensions: (json['top_dimensions'] as Map<String, dynamic>).map(
          (k, v) => MapEntry(k, (v as num).toDouble()),
        ),
        overallConfidence: (json['overall_confidence'] as num).toDouble(),
        dominantLearningStyle: json['dominant_learning_style'] as String?,
      );

  Map<String, dynamic> toJson() => {
    'student_id': studentId,
    'top_dimensions': topDimensions,
    'overall_confidence': overallConfidence,
    if (dominantLearningStyle != null)
      'dominant_learning_style': dominantLearningStyle,
  };

  @override
  List<Object?> get props => [studentId, overallConfidence];
}

