        .updateAssessmentState(updatedState)
        .storeRecommendation(report)
        .appendTurn(_turn(
          context: context,
          content: response,
          eventType: ConversationEventType.recommendationGenerated,
          isEngine: true,
        ));

    return ControllerResult(
      response: response,
      updatedMemory: updatedMemory,
      updatedPhase: updatedPhase,
      updatedLanguage: context.language,
      updatedProfile: updatedProfile,
      event: _event(ConversationEventType.recommendationGenerated),
      assessmentAdvanced: true,
      recommendationGenerated: true,
    );
  }

