/// Routes each turn to the correct handler and assembles a [ControllerResult].
final class ConversationController {
  final AnswerIntelligenceEngine _answerEngine;
  final AnswerCompletionEvaluator _completionEvaluator;
  final AdaptiveAssessmentEngine _assessmentEngine;
  final AssessmentController _assessmentController;
  final MajorMatchingEngine _matchingEngine;
  final RecommendationEngine _recommendationEngine;
  final ExplainableAIEngine _explainableEngine;
  final LLMExplanationService _explanationService;
  final List<Major> _allMajors;
  final List<Question> _allQuestions;

  static const _uuid = Uuid();

  ConversationController({
    required AnswerIntelligenceEngine answerEngine,
    required AdaptiveAssessmentEngine assessmentEngine,
    AnswerCompletionEvaluator completionEvaluator =
        const AnswerCompletionEvaluator(),
    required AssessmentController assessmentController,
    required MajorMatchingEngine matchingEngine,
    required RecommendationEngine recommendationEngine,
    required ExplainableAIEngine explainableEngine,
    required LLMExplanationService explanationService,
    required List<Major> allMajors,
    required List<Question> allQuestions,
  })  : _answerEngine = answerEngine,
        _completionEvaluator = completionEvaluator,
        _assessmentEngine = assessmentEngine,
        _assessmentController = assessmentController,
        _matchingEngine = matchingEngine,
        _recommendationEngine = recommendationEngine,
        _explainableEngine = explainableEngine,
        _explanationService = explanationService,
        _allMajors = allMajors,
        _allQuestions = allQuestions;

  // ── Primary dispatch ───────────────────────────────────────────────────────

  /// Handles a single conversation turn and returns a [ControllerResult].
  ///
  /// Async because QUL handlers may call [LLMExplanationService] which
  /// performs a network request (with timeout + local fallback).
  Future<ControllerResult> handle({
    required conv.ConversationContext context,
    required RouteDecision routeDecision,
  }) async {
    return switch (routeDecision.route) {
      ConversationRoute.continueAssessment =>
        _handleContinueAssessment(context),
      ConversationRoute.academicDiscussion =>
        _handleAcademicDiscussion(context, routeDecision),
      ConversationRoute.recommendationDiscussion =>
        _handleRecommendationDiscussion(context),
      ConversationRoute.clarification =>
        _handleClarification(context),
      ConversationRoute.greeting =>
        _handleGreeting(context),
      ConversationRoute.help =>
        _handleHelp(context),
      ConversationRoute.skipQuestion =>
        _handleSkipQuestion(context),
      ConversationRoute.restartAssessment =>
        _handleRestartAssessment(context),
      ConversationRoute.goodbye =>
        _handleGoodbye(context),
      // ── Question Understanding Layer routes ───────────────────────────────
      ConversationRoute.wordMeaning =>
        _handleWordMeaning(context),
      ConversationRoute.uncertainty =>
        _handleUncertainty(context),
      ConversationRoute.whyThisQuestion =>
        _handleWhyThisQuestion(context),
      ConversationRoute.alternativeQuestion =>
        _handleAlternativeQuestion(context),
      ConversationRoute.questionExamples =>
        _handleQuestionExamples(context),
      ConversationRoute.unknown =>
        _handleUnknown(context),
    };
  }

  // ─────────────────────────────────────────────────────────────────────────
  // Route Handlers
  // ─────────────────────────────────────────────────────────────────────────

  ControllerResult _handleContinueAssessment(conv.ConversationContext context) {
    final currentState = context.memory.assessmentState;
    final activeQuestion = context.activeQuestion;

    // Start assessment if it has not begun.
    if (currentState == null) {
      return _startAssessment(context);
    }

    // ── Conversation Completion Guard ─────────────────────────────────────
    // If there is an unresolved student need, address it before allowing
    // assessment to advance. This prevents the assessment from continuing
    // while the student still has an open question.
    if (context.phase.hasUnresolvedNeed) {
      return _resolvePendingNeed(context);
    }

    // No pending question but assessment is in progress → re-deliver the active
    // question from the current state (handles "التالي", "كمل", "واصل").
    if (activeQuestion == null) {
      final nextQ = currentState.activeQuestion;
      final response = nextQ != null
          ? _tr(context,
              ar: 'تفضل، إليك السؤال:\n\n${_formatQuestion(nextQ, context)}',
              en: 'Here is the next question:\n\n${_formatQuestion(nextQ, context)}')
          : _tr(context,
              ar: 'لقد أنهيت جميع الأسئلة. جارٍ إعداد توصياتك...',
              en: 'You have completed all questions. Preparing your recommendations...');

      final updatedMemory = _updateMemory(
        context: context,
        updatedState: currentState,
        phase: context.phase,
      );

      return ControllerResult(
        response: response,
        updatedMemory: updatedMemory,
        updatedPhase: context.phase,
        updatedLanguage: context.language,
        updatedProfile: context.profile,
        event: _event(nextQ != null
            ? ConversationEventType.questionAsked
            : ConversationEventType.engineResponse),
        assessmentAdvanced: false,
        recommendationGenerated: false,
      );
    }

    // Process the answer through the Answer Intelligence Engine.
    final decCtx = _buildDecisionContext(context, currentState);
    final processingResult = _answerEngine.process(
      rawAnswer: context.studentMessage,
      activeQuestion: activeQuestion,
      profile: context.profile,
      context: decCtx,
      decisionResult: context.decision,
      history: currentState.answerHistory,
    );

    // ── Answer Completion Gate ─────────────────────────────────────────
    // The assessment MUST NOT advance until the evaluator confirms the
    // current question has been answered sufficiently.
    //
    // The gate reads exclusively from already-computed data (features, score)
    // — it performs no additional NLP or scoring.
    if (processingResult.features != null && processingResult.score != null) {
      final completionCtx = AnswerCompletionContext.build(
        question: activeQuestion,
        rawAnswer: context.studentMessage,
        features: processingResult.features!,
        score: processingResult.score!,
        recentHistory: context.memory.contextWindow(context.policy),
        clarificationsOnThisQuestion: context.phase.clarificationCount,
        language: context.language.active,
      );

      final evaluation = _completionEvaluator.evaluate(completionCtx);

      if (!evaluation.allowsAdvancement) {
        return _handleIncompleteAnswer(
          context: context,
          evaluation: evaluation,
          activeQuestion: activeQuestion,
          currentState: currentState,
        );
      }
    }

    // ── Advance the assessment (gate approved) ────────────────────────────
    // Reconstruct the full QuestionHistory from the current AssessmentState so
    // QuestionSelector sees ALL previously asked questions — not just this turn.
    final turnResult = _assessmentEngine.advance(
      currentState: currentState,
      processingResult: processingResult,
      questionHistory: _buildQuestionHistory(currentState),
      allQuestions: _allQuestions,
      context: decCtx,
    );

    final updatedState = turnResult.updatedState;
    final updatedProfile =
        processingResult.updatedProfile ?? context.profile;

    // Check if assessment completed → trigger recommendation.
    if (turnResult.assessmentCompleted) {
      return _generateRecommendation(
        context: context,
        updatedState: updatedState,
        updatedProfile: updatedProfile,
        stats: turnResult.statistics,
      );
    }

    // Build response for next question.
    final nextQ = turnResult.nextQuestion;
    final response = nextQ == null
        ? _tr(context,
            ar: 'شكراً على إجابتك. هل تريد مواصلة التقييم؟',
            en: 'Thank you for your answer. Shall we continue the assessment?')
        : _formatQuestion(nextQ, context);

    final updatedMemory = _updateMemory(
      context: context,
      updatedState: updatedState,
      phase: context.phase,
    );

    return ControllerResult(
      response: response,
      updatedMemory: updatedMemory,
      updatedPhase: context.phase,
      updatedLanguage: context.language,
      updatedProfile: updatedProfile,
      event: _event(ConversationEventType.questionAnswered,
          intent: context.decision.detectedIntent.name),
      assessmentAdvanced: true,
      recommendationGenerated: false,
    );
  }

  // ─────────────────────────────────────────────────────────────────────────
  // Answer Completion Gate — Incomplete Answer Handler
  // ─────────────────────────────────────────────────────────────────────────

  /// Called when [AnswerCompletionEvaluator] returns a non-advancing result.
  ///
  /// Branches on [CompletionReason] (the extensible inner layer):
  ///   - Re-routes to QUL/meta handlers when the message is not an answer.
  ///   - Builds a targeted probe response for partial/insufficient answers.
  ///   - Repeats the question after every non-advancing response so the
  ///     student always has the question in view.
  ///
  /// The assessment NEVER advances from this method.
  ControllerResult _handleIncompleteAnswer({
    required conv.ConversationContext context,
    required CompletionEvaluation evaluation,
    required Question activeQuestion,
    required AssessmentState currentState,
  }) {
    switch (evaluation.reason) {
      // ─ Re-route to existing QUL infrastructure ───────────────────────────────

      case CompletionReason.clarificationRequest:
        // The message is a question. Route to the clarification handler
        // which will explain and re-present the assessment question.
        return _simple(
          context: context,
          response: _tr(context,
              ar: 'فهمت سؤالك. '
                  '${_tr(context, ar: "لنفس السؤال", en: "For the same question")} — '
                  '${_formatQuestion(activeQuestion, context)}',
              en: 'I understand your question. '
                  'For the same question — '
                  '${_formatQuestion(activeQuestion, context)}'),
          eventType: ConversationEventType.questionExplained,
          assessmentAdvanced: false,
        );

      case CompletionReason.metaQuestion:
        // The student is asking about the assessment itself.
        // Acknowledge, then re-present the question.
        final metaAr = 'سؤال وجيه — هذا التقييم يساعدني أن أفهم ميولك وقدراتك'
            ' لأقترح عليك التخصص الأنسب.'
            ' لا توجد إجابة خاطئة هنا.'
            '\n\n${_formatQuestion(activeQuestion, context)}';
        final metaEn = 'Good question — this assessment helps me understand'
            ' your strengths and interests so I can suggest the most'
            ' suitable major for you.'
            ' There are no right or wrong answers.'
            '\n\n${_formatQuestion(activeQuestion, context)}';
        return _simple(
          context: context,
          response: _tr(context, ar: metaAr, en: metaEn),
          eventType: ConversationEventType.questionExplained,
          assessmentAdvanced: false,
        );

      // ─ Probe responses (assessment does NOT advance) ─────────────────────

      case CompletionReason.insufficientContent:
        // The answer has too little content to evaluate.
        // Build a targeted, question-type-aware gap message.
        final probe = _tr(context,
            ar: 'شكراً لإجابتك. ${evaluation.gap ?? "هل يمكنك توضيح إجابتك قليلاً؟"}\n\n${_formatQuestion(activeQuestion, context)}',
            en: 'Thank you. ${evaluation.gap ?? "Could you clarify your answer a little?"}\n\n${_formatQuestion(activeQuestion, context)}');
        return _simple(
          context: context,
          response: probe,
          eventType: ConversationEventType.questionExplained,
          assessmentAdvanced: false,
        );

      case CompletionReason.partialAnswer:
      case CompletionReason.lowEvaluatorConfidence:
        // The answer is a start but needs more depth, OR the evaluator
        // was not confident enough. Both get one probe turn.
        final probe = _tr(context,
            ar: 'شكراً. ${evaluation.gap ?? "هل يمكنك إخباري أكثر قليلاً؟"}\n\n${_formatQuestion(activeQuestion, context)}',
            en: 'Thank you. ${evaluation.gap ?? "Could you tell me a little more?"}\n\n${_formatQuestion(activeQuestion, context)}');
        // Mark this as a clarification turn so the NEXT message from the student
        // is accepted as a complete answer regardless of its content.
        // This prevents an infinite probe loop.
        final updatedPhase = context.phase.addClarification();
        final updatedMemory = _updateMemory(
          context: context,
          updatedState: currentState,
          phase: updatedPhase,
        );
        return ControllerResult(
          response: probe,
          updatedMemory: updatedMemory,
          updatedPhase: updatedPhase,
          updatedLanguage: context.language,
          updatedProfile: context.profile,
          event: _event(ConversationEventType.questionExplained),
          assessmentAdvanced: false,
          recommendationGenerated: false,
        );

      case CompletionReason.accepted:
        // Unreachable — accepted only appears with CompletionState.complete,
        // which is handled before _handleIncompleteAnswer is called.
        throw StateError(
            'CompletionReason.accepted reached _handleIncompleteAnswer. '
            'This is a bug in AnswerCompletionEvaluator.');
    }
  }

  ControllerResult _startAssessment(conv.ConversationContext context) {
    // Use _assessmentEngine.begin() — not _assessmentController.start().
    // begin() selects the first question via the question selector.
    // _assessmentController.start() only creates a bare state with no question.
    final state = _assessmentEngine.begin(
      studentId: context.studentId,
      profile: context.profile,
      allQuestions: _allQuestions,
    );

    final firstQuestion = state.activeQuestion;
    final response = firstQuestion == null
        ? _tr(context,
            ar: 'سنبدأ التقييم الأكاديمي الآن. لا توجد أسئلة محملة حالياً — سيتم تحميل قاعدة المعرفة قريباً.',
            en: 'We will begin the assessment now. No questions are loaded yet — the knowledge base will be loaded soon.')
        : _tr(context,
            ar: 'رائع! لنبدأ تقييمك الأكاديمي.\n\n${_formatQuestion(firstQuestion, context)}',
            en: 'Great! Let\'s begin your academic assessment.\n\n${_formatQuestion(firstQuestion, context)}');

    final updatedMemory = context.memory
        .updateAssessmentState(state)
        .appendTurn(_turn(
          context: context,
          content: response,
          eventType: ConversationEventType.questionAsked,
          isEngine: true,
        ));

    return ControllerResult(
      response: response,
      updatedMemory: updatedMemory,
      updatedPhase: context.phase.transitionTo(ConversationStage.assessment),
      updatedLanguage: context.language,
      updatedProfile: context.profile,
      event: _event(ConversationEventType.questionAsked),
      assessmentAdvanced: false,
      recommendationGenerated: false,
    );
  }

  // ─────────────────────────────────────────────────────────────────────────
  // Conversation Completion — Pending Need Resolution
  // ─────────────────────────────────────────────────────────────────────────

  /// Called when [ConversationPhase.pendingNeed] is non-null and the student
  /// sends another message.
  ///
  /// The student's new message may be:
  ///   (a) An answer to the pending need (e.g. follow-up to an example
  ///       validation) → clear the need, then repeat the question.
  ///   (b) Another question → address it and keep the need open.
  ///
  /// This handler NEVER advances the assessment.
  ControllerResult _resolvePendingNeed(conv.ConversationContext context) {
    final need = context.phase.pendingNeed!;
    final activeQuestion = context.activeQuestion;

    switch (need) {
      case ExampleValidationNeed(:final studentExample):
        // The student had asked "Does X count?" — now confirm it and
        // re-present the assessment question for their actual answer.
        final confirm = _tr(context,
            ar: 'نعم، "$studentExample" هو مثال جيد تماماً ويمكنك الإجابة بناءً عليه.',
            en: 'Yes, "$studentExample" is a perfectly valid example and you can base your answer on it.');
        final questionBlock = activeQuestion != null
            ? '\n\n${_formatQuestion(activeQuestion, context)}'
            : '';
        final updatedPhase = context.phase.withNeedResolved();
        final updatedMemory = _updateMemory(
          context: context,
          updatedState: context.memory.assessmentState,
          phase: updatedPhase,
        );
        return ControllerResult(
          response: '$confirm$questionBlock',
          updatedMemory: updatedMemory,
          updatedPhase: updatedPhase,
          updatedLanguage: context.language,
          updatedProfile: context.profile,
          event: _event(ConversationEventType.questionExplained),
          assessmentAdvanced: false,
          recommendationGenerated: false,
        );

      case FollowUpClarificationNeed(:final followUpQuestion):
        // The student had a follow-up after an explanation — answer it,
        // then re-present the question. Need is now resolved.
        final answer = _tr(context,
            ar: 'سؤال وجيه — "$followUpQuestion". '
                'يمكنك الإجابة بأي شكل يعكس وجهة نظرك الحقيقية، '
                'لا توجد إجابة خاطئة هنا.',
            en: 'Good question — "$followUpQuestion". '
                'You can answer in any way that reflects your genuine perspective, '
                'there is no wrong answer here.');
        final questionBlock = activeQuestion != null
            ? '\n\n${_formatQuestion(activeQuestion, context)}'
            : '';
        final updatedPhase = context.phase.withNeedResolved();
        final updatedMemory = _updateMemory(
          context: context,
          updatedState: context.memory.assessmentState,
          phase: updatedPhase,
        );
        return ControllerResult(
          response: '$answer$questionBlock',
          updatedMemory: updatedMemory,
          updatedPhase: updatedPhase,
          updatedLanguage: context.language,
          updatedProfile: context.profile,
          event: _event(ConversationEventType.questionExplained),
          assessmentAdvanced: false,
          recommendationGenerated: false,
        );
    }
  }

  Future<ControllerResult> _handleAcademicDiscussion(
    conv.ConversationContext context,
    RouteDecision routeDecision,
  ) async {
    // Use LLM for academic responses when available; fall back to template.
    final response = await _buildAcademicResponseLlm(context);

    // Return-to-assessment bridge message.
    final returnBridge = context.policy.autoReturnAfterDiscussion &&
            context.phase.stage.canReceiveAnswer &&
            context.activeQuestion != null
        ? '\n\n${_tr(context, ar: "لنعد إلى التقييم:", en: "Let us return to the assessment:")}\n${_formatQuestion(context.activeQuestion!, context)}'
        : '';

    final updatedPhase = context.phase
        .interrupt()
        .incrementDiscussionDepth();

    final updatedMemory = _updateMemory(
      context: context,
      updatedState: context.memory.assessmentState,
      phase: updatedPhase,
    );

    return ControllerResult(
      response: '$response$returnBridge',
      updatedMemory: updatedMemory,
      updatedPhase: routeDecision.willReturnToAssessment
          ? updatedPhase.resumeFromInterruption()
          : updatedPhase,
      updatedLanguage: context.language,
      updatedProfile: context.profile,
      event: _event(ConversationEventType.academicDiscussion,
          intent: context.decision.detectedIntent.name),
      assessmentAdvanced: false,
      recommendationGenerated: false,
    );
  }

  ControllerResult _handleRecommendationDiscussion(
      conv.ConversationContext context) {
    final report = context.memory.recommendationReport;
    if (report == null) {
      return _simple(
        context: context,
        response: _tr(context,
            ar: 'لم يتم إنشاء توصية بعد. سنكمل التقييم أولاً.',
            en: 'No recommendation has been generated yet. Let\'s complete the assessment first.'),
        eventType: ConversationEventType.recommendationDiscussed,
        assessmentAdvanced: false,
      );
    }

    final response = _buildRecommendationDiscussionResponse(
        context, report);

    final updatedPhase =
        context.phase.transitionTo(ConversationStage.postRecommendation);

    final updatedMemory = _updateMemory(
      context: context,
      updatedState: context.memory.assessmentState,
      phase: updatedPhase,
    );

    return ControllerResult(
      response: response,
      updatedMemory: updatedMemory,
      updatedPhase: updatedPhase,
      updatedLanguage: context.language,
      updatedProfile: context.profile,
      event: _event(ConversationEventType.recommendationDiscussed),
      assessmentAdvanced: false,
      recommendationGenerated: false,
    );
  }

  Future<ControllerResult> _handleClarification(conv.ConversationContext context) async {
    final activeQuestion = context.activeQuestion;
    if (activeQuestion == null) {
      return _simple(
        context: context,
        response: _tr(context,
            ar: 'لا يوجد سؤال نشط حالياً لشرحه.',
            en: 'There is no active question to explain right now.'),
        eventType: ConversationEventType.questionExplained,
        assessmentAdvanced: false,
      );
    }

    final recentHistory = context.memory.contextWindow(context.policy);
    final explanation = await _explanationService.generate(
      intent: QulIntent.clarification,
      question: activeQuestion,
      studentMessage: context.studentMessage,
      isArabic: context.isArabic,
      recentHistory: recentHistory,
      clarificationCount: context.phase.clarificationCount,
    );

    final repeat = context.policy.repeatQuestionAfterExplanation
        ? '\n\n${_formatQuestion(activeQuestion, context)}'
        : '';

    final updatedPhase = context.phase.addClarification();
    final updatedMemory = _updateMemory(
      context: context,
      updatedState: context.memory.assessmentState,
      phase: updatedPhase,
    );

    return ControllerResult(
      response: '$explanation$repeat',
      updatedMemory: updatedMemory,
      updatedPhase: updatedPhase,
      updatedLanguage: context.language,
      updatedProfile: context.profile,
      event: _event(ConversationEventType.questionExplained),
      assessmentAdvanced: false,
      recommendationGenerated: false,
    );
  }

  ControllerResult _handleGreeting(conv.ConversationContext context) {
    final response = _tr(context,
        ar: 'أهلاً وسهلاً! أنا مستشارك الأكاديمي الذكي. هنا لمساعدتك في اكتشاف أفضل التخصصات التي تناسب شخصيتك وقدراتك.',
        en: 'Welcome! I am your AI academic advisor. I\'m here to help you discover the best majors that match your personality and abilities.');

    return _simple(
      context: context,
      response: response,
      eventType: ConversationEventType.greeting,
      assessmentAdvanced: false,
    );
  }

  ControllerResult _handleHelp(conv.ConversationContext context) {
    final response = _tr(context,
        ar: 'يمكنني مساعدتك في:\n- الإجابة على أسئلة التقييم\n- الإجابة على أسئلتك الأكاديمية\n- شرح أي سؤال\n- تخطي سؤال\n- مناقشة التوصيات الأكاديمية',
        en: 'I can help you with:\n- Answering assessment questions\n- Answering your academic questions\n- Explaining any question\n- Skipping a question\n- Discussing academic recommendations');

    return _simple(
      context: context,
      response: response,
      eventType: ConversationEventType.engineResponse,
      assessmentAdvanced: false,
    );
  }

  ControllerResult _handleSkipQuestion(conv.ConversationContext context) {
    final state = context.memory.assessmentState;
    if (state == null || context.activeQuestion == null) {
      return _handleGreeting(context);
    }

    // Delegate entirely to AdaptiveAssessmentEngine.skip().
    // This is the ONLY component authorised to select the next question.
    // No inline question filter here — QuestionSelector handles it with full
    // phase/coverage/gap awareness.
    final skipResult = _assessmentEngine.skip(
      currentState: state,
      allQuestions: _allQuestions,
    );

    final updatedState = skipResult.updatedState;
    final nextQ = skipResult.nextQuestion;

    final response = nextQ != null
        ? '${_tr(context, ar: "تم تخطي السؤال.", en: "Question skipped.")}\n\n${_formatQuestion(nextQ, context)}'
