  ControllerResult _handleRestartAssessment(conv.ConversationContext context) {
    final freshProfile =
        StudentCognitiveProfile.initial(studentId: context.studentId);

    // Use _assessmentEngine.restart() — NOT _assessmentController.start().
    // restart() calls begin() internally, which runs QuestionSelector and
    // sets the first question immediately. start() alone leaves activeQuestion null.
    final existingState = context.memory.assessmentState ??
        _assessmentController.start(
          studentId: context.studentId,
          profile: freshProfile,
        );

    final newState = _assessmentEngine.restart(
      state: existingState,
      freshProfile: freshProfile,
      allQuestions: _allQuestions,
    );

    final firstQ = newState.activeQuestion;
    final response = _tr(context,
        ar: 'تم إعادة التقييم من البداية.\n\n${firstQ != null ? _formatQuestion(firstQ, context) : ""}',
        en: 'Assessment restarted from the beginning.\n\n${firstQ != null ? _formatQuestion(firstQ, context) : ""}');

    final updatedMemory = ConversationMemory.empty(context.sessionId)
        .updateAssessmentState(newState);
    final updatedPhase = ConversationPhase.initial()
        .transitionTo(ConversationStage.assessment);

    return ControllerResult(
      response: response,
      updatedMemory: updatedMemory,
      updatedPhase: updatedPhase,
      updatedLanguage: context.language,
      updatedProfile: freshProfile,
      event: _event(ConversationEventType.assessmentRestarted),
      assessmentAdvanced: false,
