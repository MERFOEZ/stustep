/// SAIE — ConversationController
///
/// Orchestrates the complete conversation lifecycle.
/// Handles each route dispatched by the [ConversationRouter]:
///   - continueAssessment   → runs Answer Intelligence + Assessment Engine
///   - academicDiscussion   → answers academic question, returns to assessment
///   - recommendationDiscussion → answers questions about the recommendation
///   - clarification        → explains, repeats question
///   - greeting / goodbye   → appropriate response
///   - skipQuestion         → skips, asks next
///   - restartAssessment    → resets assessment state
///   - unknown / help       → polite redirect
///
/// The controller is purely functional: it takes a [ConversationContext] and
/// returns an updated [ControllerResult]. No state is held internally.
