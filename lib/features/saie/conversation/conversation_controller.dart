  ControllerResult _simple({
    required conv.ConversationContext context,
    required String response,
    required ConversationEventType eventType,
    required bool assessmentAdvanced,
  }) {
    final updatedMemory = _updateMemory(
      context: context,
      updatedState: context.memory.assessmentState,
      phase: context.phase,
    );
    return ControllerResult(
      response: response,
      updatedMemory: updatedMemory,
      updatedPhase: context.phase,
      updatedLanguage: context.language,
      updatedProfile: context.profile,
      event: _event(eventType),
      assessmentAdvanced: assessmentAdvanced,
      recommendationGenerated: false,
    );
  }

  ConversationMemory _updateMemory({
    required conv.ConversationContext context,
    required AssessmentState? updatedState,
    required ConversationPhase phase,
  }) {
    var memory = context.memory;
    if (updatedState != null) {
      memory = memory.updateAssessmentState(updatedState);
    }

    // Auto-summarise if due.
    if (memory.shouldSummarise(context.policy)) {
      final turns = memory.turnsSinceLastSummary();
      if (turns.isNotEmpty) {
        final summary = ConversationSummary.generate(
          summaryId: _uuid.v4(),
          sessionId: context.sessionId,
          turns: turns,
          phase: phase,
          profile: context.profile,
        );
        memory = memory.addSummary(summary);
      }
    }

    return memory;
  }

