  String _buildRecommendationDiscussionResponse(
    conv.ConversationContext ctx,
    RecommendationReport report,
  ) {
    final topPick = report.topPick;
    if (topPick == null) {
      return _tr(ctx,
          ar: 'لم يتم التوصية بأي تخصص بعد. يحتاج التقييم إلى مزيد من الأسئلة.',
          en: 'No major has been recommended yet. The assessment needs more questions.');
    }

    final msg = ctx.studentMessage.toLowerCase();
    if (msg.contains('لماذا') ||
        msg.contains('why') ||
        msg.contains('how come')) {
      final strengthLabels = topPick.topStrengths
          .take(3)
          .map((k) => _friendlyDimensionLabel(k, ctx.isArabic))
          .join(ctx.isArabic ? '، ' : ', ');
      return _tr(ctx,
          ar: 'تم اختيار "${topPick.majorName}" لأنه يتناسب مع قدراتك الأكاديمية بنسبة ${topPick.similarityScore}%. نقاط قوتك في: $strengthLabels.',
          en: '"${topPick.majorName}" was selected because it matches your academic abilities by ${topPick.similarityScore}%. Your key strengths: $strengthLabels.');
    }

    if (msg.contains('وظيفة') ||
        msg.contains('مهنة') ||
        msg.contains('job') ||
        msg.contains('career')) {
      return _tr(ctx,
          ar: 'تخصص "${topPick.majorName}" يفتح أمامك فرص مهنية عديدة. لمعرفة التفاصيل، تحدث مع المرشد الأكاديمي في جامعتك.',
          en: 'The "${topPick.majorName}" major opens many career opportunities. For details, speak with your university\'s academic advisor.');
    }

    if (msg.contains('صعب') ||
        msg.contains('صعوبة') ||
        msg.contains('difficult') ||
        msg.contains('hard')) {
      return _tr(ctx,
          ar: 'كل تخصص له تحدياته، لكن مع تطابق قدراتك مع "${topPick.majorName}" بنسبة ${topPick.similarityScore}%، ستكون قادراً على التفوق.',
          en: 'Every major has its challenges, but with your ${topPick.similarityScore}% match with "${topPick.majorName}", you will be able to excel.');
    }

    // Generic discussion response.
    final reasons = topPick.reasons.take(2).map((r) => r.title).join(', ');
    return _tr(ctx,
        ar: 'توصيتك هي "${topPick.majorName}" بنسبة تطابق ${topPick.similarityScore}%. الأسباب الرئيسية: $reasons. هل لديك سؤال محدد؟',
        en: 'Your recommendation is "${topPick.majorName}" with a ${topPick.similarityScore}% match score. Key reasons: $reasons. Do you have a specific question?');
  }

