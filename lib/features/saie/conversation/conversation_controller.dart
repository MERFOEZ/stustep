  /// Formats the active assessment question for display to the student.
  ///
  /// Always shows the question text. Appends:
  ///   - The hint line when present (e.g. "اختر ما ينطبق عليك").
  ///   - The numbered answer options when defined (multiple-choice / multi-select).
  ///
  /// This makes the repeated question block self-contained so the student
  /// never has to scroll back to see the options.
  String _formatQuestion(Question q, conv.ConversationContext ctx) {
    final buf = StringBuffer(q.text);

    // Append hint when provided.
    if (q.hint != null && q.hint!.trim().isNotEmpty) {
      buf.write('\n${q.hint!.trim()}');
    }

    // Append numbered options for structured question types.
    if (q.options.isNotEmpty) {
      buf.write('\n');
      for (var i = 0; i < q.options.length; i++) {
        buf.write('\n${i + 1}. ${q.options[i].label}');
      }
    }

    return buf.toString();
  }




