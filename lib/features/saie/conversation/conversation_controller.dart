  // Example Validation Detector
  // ─────────────────────────────────────────────────────────────────────────

  /// Detects whether the student's message is asking if a specific example
  /// is valid as an answer ("هل التنمر يُعتبر قيادة؟", "Does bullying count?").
  ///
  /// Returns the extracted candidate example string, or null if not detected.
  String? _extractExampleValidationCandidate(String message) {
    final msg = message.trim();

    // Arabic validation patterns
    final arPatterns = [
      RegExp(r'هل\s+(.+?)\s+(يُعدّ|يُعد|يعتبر|يحسب|يصلح|يُصنّف|يندرج)', unicode: true),
      RegExp(r'(.+?)\s+(تُعدّ|تعتبر|تحسب|تصلح)\s+(قيادة|إبداعاً|بحثاً|تواصلاً|مثالاً)', unicode: true),
      RegExp(r'يعني\s+(.+?)\s+(يصلح|يحسب|تحسب|يُعدّ)؟?$', unicode: true),
      RegExp(r'مثل\s+(.+?)\s+(يصلح|يحسب|يُعدّ)\s+(هنا|للإجابة)', unicode: true),
    ];

    // English validation patterns
    final enPatterns = [
      RegExp(r'(?:does|do|would)\s+(.+?)\s+(?:count|qualify|work)\b', caseSensitive: false),
      RegExp(r'(?:is|are)\s+(.+?)\s+(?:an?|considered?|valid)\s+(?:example|answer)', caseSensitive: false),
      RegExp(r'(?:can I|could I)\s+(?:use|say|mention)\s+(.+?)\??$', caseSensitive: false),
    ];

    for (final pattern in [...arPatterns, ...enPatterns]) {
      final match = pattern.firstMatch(msg);
      if (match != null) {
        final candidate = match.group(1)?.trim();
        if (candidate != null && candidate.length >= 2) {
          return candidate;
        }
      }
    }
    return null;
  }

