    );

    final report = _recommendationEngine.produce(
      studentId: context.studentId,
      profile: updatedProfile,
      ranking: ranking,
      stats: stats,
    );

    final explainableReport = _explainableEngine.explain(
      report: report,
      profile: updatedProfile,
      ranking: ranking,
    );

    final response = _formatRecommendationResponse(
        report, explainableReport, context);

    final updatedPhase =
        context.phase.transitionTo(ConversationStage.recommendation);

