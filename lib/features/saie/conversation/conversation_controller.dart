  // ─── Question History Reconstruction ─────────────────────────────────────

  /// Rebuilds a [QuestionHistory] from the ids stored in [AssessmentState].
  ///
  /// This gives [QuestionSelector] full visibility into ALL previously asked
  /// questions — not just the one answered in the current turn.
  ///
  /// Domain keys are resolved from [_allQuestions] when possible. Questions
  /// that no longer exist in the pool are recorded with empty domain keys;
  /// that is safe because they are already excluded by the asked-ids filter.
  QuestionHistory _buildQuestionHistory(AssessmentState state) {
    final questionIndex = {for (final q in _allQuestions) q.id: q};
    final now = DateTime.now().toUtc();

    final records = <QuestionRecord>[];

    // All asked (answered + skipped) questions go in first.
    for (final id in state.askedQuestionIds) {
      final q = questionIndex[id];
      final isSkipped = state.skippedQuestionIds.contains(id);
      records.add(QuestionRecord(
        questionId: id,
        outcome:
            isSkipped ? QuestionOutcome.skipped : QuestionOutcome.answered,
        askedAt: now,
        domainKeys: q?.targetDomainIds ?? const [],
      ));
    }

    return QuestionHistory(records: records);
  }
