  /// [SupportedIntent.expressUncertainty] — student says they don't know.
  /// LLM simplifies + provides examples. After 2 clarifications, escalates to skip().
  /// Assessment state: only mutated via _assessmentEngine.skip() if escalating.
  Future<ControllerResult> _handleUncertainty(conv.ConversationContext context) async {
    final activeQuestion = context.activeQuestion;
    if (activeQuestion == null) {
      return _simple(
        context: context,
        response: _tr(context,
            ar: 'لا يوجد سؤال نشط حالياً.',
            en: 'There is no active question right now.'),
        eventType: ConversationEventType.questionExplained,
        assessmentAdvanced: false,
      );
    }

    const maxBeforeEscalation = 2;
    final clarificationsSoFar = context.phase.clarificationCount;

    if (clarificationsSoFar >= maxBeforeEscalation) {
      // Escalate: skip() is the ONLY mutation — assessment engine stays in control.
      final state = context.memory.assessmentState!;
      final skipResult = _assessmentEngine.skip(
        currentState: state,
        allQuestions: _allQuestions,
        preferredDomainIds: activeQuestion.targetDomainIds,
      );
      final updatedState = skipResult.updatedState;
      final nextQ = skipResult.nextQuestion;
      final intro = _tr(context,
          ar: 'لا بأس — لننتقل لسؤال مشابه:\n\n',
          en: 'No worries — let\'s try a related question:\n\n');
      final response = nextQ != null
          ? '$intro${_formatQuestion(nextQ, context)}'
          : _tr(context,
              ar: 'لا مشكلة — لقد أجبت على ما يكفي. سيتم إعداد توصياتك الآن.',
              en: 'No problem — you\'ve answered enough. Preparing your recommendations now.');
      final updatedPhase =
          context.phase.addClarification().copyWith(clarificationCount: 0);
      final updatedMemory = _updateMemory(
        context: context,
        updatedState: updatedState,
        phase: updatedPhase,
      );
      return ControllerResult(
        response: response,
        updatedMemory: updatedMemory,
        updatedPhase: updatedPhase,
        updatedLanguage: context.language,
        updatedProfile: context.profile,
        event: _event(ConversationEventType.questionSkipped),
        assessmentAdvanced: true,
        recommendationGenerated: false,
      );
    }

    // First or second attempt: LLM simplifies the question.
    final recentHistory = context.memory.contextWindow(context.policy);
    final simplified = await _explanationService.generate(
      intent: QulIntent.uncertainty,
      question: activeQuestion,
      studentMessage: context.studentMessage,
      isArabic: context.isArabic,
      recentHistory: recentHistory,
      clarificationCount: clarificationsSoFar,
    );
    final updatedPhase = context.phase.addClarification();
    final updatedMemory = _updateMemory(
      context: context,
      updatedState: context.memory.assessmentState,
      phase: updatedPhase,
    );
    return ControllerResult(
      response: simplified,
      updatedMemory: updatedMemory,
      updatedPhase: updatedPhase,
      updatedLanguage: context.language,
      updatedProfile: context.profile,
      event: _event(ConversationEventType.questionExplained),
      assessmentAdvanced: false,
      recommendationGenerated: false,
    );
  }

