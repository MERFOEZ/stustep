  ControllerResult _generateRecommendation({
    required conv.ConversationContext context,
    required AssessmentState updatedState,
    required StudentCognitiveProfile updatedProfile,
    required dynamic stats,
  }) {
    final ranking = _matchingEngine.match(
      profile: updatedProfile,
