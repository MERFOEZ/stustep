import 'dart:typed_data';

/// ملف اختاره المستخدم، ممثَّلاً **ببياناته لا بمساره**.
///
/// **لماذا لا نمرّر `File` من `dart:io`؟**
/// لأن `dart:io` لا يعمل على الويب: `File(path)` ترمي `UnsupportedError`،
/// و`FilePicker` على الويب يُعيد `path == null` دائماً فيفشل الاختيار صامتاً.
/// وبما أن التطبيق صار يُنشر على الويب أيضاً، كان لا بد أن يتحدّث الموديول
/// عن الملفات بلغة واحدة تعمل على المنصات الثلاث: البايتات والاسم.
///
/// المكسب الثاني أن طبقة الخدمات لم تعد تعرف نظام الملفات إطلاقاً، فصارت
/// قابلة للاختبار بمعطيات في الذاكرة بلا ملفات حقيقية على القرص.
class UploadFile {
  /// اسم الملف الأصلي كما اختاره المستخدم — يُعرض له ويُخزَّن في الوثيقة.
  final String name;

  final Uint8List bytes;

  const UploadFile({required this.name, required this.bytes});

  /// الحجم بالبايت — يُقرأ من البيانات نفسها بلا استعلام نظام الملفات.
  int get sizeBytes => bytes.length;
}
